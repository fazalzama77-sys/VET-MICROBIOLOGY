  function attachImages(bank) {
    if (!bank) return;
    Object.keys(bank).forEach(function (unitId) {
      var unitObj = bank[unitId] || {};
      Object.keys(unitObj).forEach(function (topicId) {
        var figs = topicImages[topicId];
        if (figs && figs.length) {
          var topic = unitObj[topicId];
          topic.img = figs[0].url;
          topic.figures = figs;
        }
      });
    });
  }
